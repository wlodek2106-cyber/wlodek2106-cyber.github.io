const assert=require("node:assert/strict");
const fs=require("node:fs");
const vm=require("node:vm");
const path=require("node:path");
const html=fs.readFileSync(path.join(__dirname,"../backend/dashboard.html"),"utf8");
const start=html.indexOf("function marketingExport("), end=html.indexOf("\nasync function marketingStudio(",start);
assert.ok(start>=0&&end>start);
const convert=vm.runInNewContext("("+html.slice(start,end)+")");
const data={campaigns:[{id:1,title:"Кампания, тест"}],items:[{id:3,campaign_id:1,day:"2026-11-25",platform:"x",status:"draft",title:" =1+1",caption:"a\r\nBEGIN:VEVENT; "+ "Я".repeat(100)+"😀".repeat(30),hashtags:"#тест",asset_notes:'a"b'},{id:4,campaign_id:1,day:"2026-11-26",platform:"youtube",status:"cancelled",title:"cancel"}]};
const csv=convert(data,"csv");
assert.ok(csv.startsWith("\uFEFF"));
assert.ok(csv.includes("\"' =1+1\""));
assert.ok(csv.includes('"a""b"'));
assert.ok(csv.includes('"Кампания, тест"'));
const ics=convert(data,"ics",new Date("2026-11-25T00:00:00Z"));
assert.ok(ics.startsWith("BEGIN:VCALENDAR\r\n"));
assert.ok(ics.includes("DTSTAMP:20261125T000000Z"));
assert.ok(ics.includes("DTSTART;VALUE=DATE:20261125"));
assert.ok(ics.includes("STATUS:TENTATIVE"));
assert.ok(ics.includes("STATUS:CANCELLED"));
assert.equal(ics.match(/^BEGIN:VEVENT$/gm).length,2);
assert.ok(ics.split("\r\n").every(l=>Buffer.byteLength(l,"utf8")<=75));
assert.ok(ics.replace(/\r\n /g,"").includes("a\\nBEGIN:VEVENT\\;"));
assert.ok(convert({campaigns:[],items:[]},"ics").endsWith("END:VCALENDAR\r\n"));
assert.throws(()=>convert(data,"unknown"),/Unsupported/);
console.log("PASS: Marketing CSV and ICS exports");
